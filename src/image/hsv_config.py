from enum import Enum


class HSVRange(tuple, Enum):
    # ((h_min, s_min, v_min), (h_max, s_max, v_max))
    # 白色文本，特殊典例:上滑索时，可移动但未锁定到的滑索距离数字文本
    WHITE = (((0, 0, 200), (180, 50, 255)),)
    # 黄色文本，特殊典例:上滑索时，可移动且已被锁定到的滑索距离数字文本
    GOLD_TEXT = (((15, 40, 180), (60, 180, 255)),)
    # 灰色文本，特殊典例:倒卖页面的价格文本和好友名称
    DARK_GRAY_TEXT = (((0, 0, 40), (180, 30, 90)),)
    # 延迟显示信号条（主界面左下角），不透明纯色 UI，跨背景逐像素一致。
    # 实测 40 张截图全为绿（H≈71，S≈224 V≈231）；黄/红为高延迟状态的
    # 防御性预留（网络质量变色是延迟指示的通行做法，样本未覆盖）。
    # S/V 阈值取高以排除场景渗色：草地绿 H≈33-36 S≈130、面板渗色
    # 青蓝 H≈101-112、暗草 V≈96，均不落入以下任何一段。
    SIGNAL_BARS = (
        ((60, 150, 80), (90, 255, 255)),    # 绿：网络良好
        ((15, 180, 150), (45, 255, 255)),   # 黄/橙：延迟升高（预留）
        ((0, 180, 100), (10, 255, 255)),    # 红：高延迟（预留）
        ((170, 180, 100), (180, 255, 255)),  # 红（跨 H 0° 两端）
    )
